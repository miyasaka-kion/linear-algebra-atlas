// Sort once by descending kanji length so longer compounds always win
const SORTED_DICT = [...FURIGANA_DICT].sort((a, b) => b[0].length - a[0].length);
const REGEX = new RegExp(
  SORTED_DICT.map(([k]) => k.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|'),
  'g'
);
const MAP = new Map<string, string>(SORTED_DICT);

interface JaTextProps {
  text: string;
  furigana: boolean;
}

export const JaText: React.FC<JaTextProps> = ({ text, furigana }) => {
  const nodes = useMemo(() => {
    if (!furigana) return null;
    const result: React.ReactNode[] = [];
    let lastIndex = 0;
    let key = 0;
    REGEX.lastIndex = 0;
    let match: RegExpExecArray | null;
    while ((match = REGEX.exec(text)) !== null) {
      if (match.index > lastIndex) {
        result.push(text.slice(lastIndex, match.index));
      }
      const kanji = match[0];
      const reading = MAP.get(kanji);
      if (reading) {
        result.push(
          <ruby key={key++}>
            {kanji}
            <rt>{reading}</rt>
          </ruby>
        );
      } else {
        result.push(kanji);
      }
      lastIndex = match.index + kanji.length;
    }
    if (lastIndex < text.length) {
      result.push(text.slice(lastIndex));
    }
    return result;
  }, [text, furigana]);

  return <>{furigana ? nodes : text}</>;
};
